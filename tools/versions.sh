#!/bin/sh
# Release history: which versions were published, and how they get back into the
# tree that is being published.
#
#   sh tools/versions.sh next                      # the version this build carries
#   sh tools/versions.sh list                      # what has been published
#   sh tools/versions.sh archive <pkgdir> <ver>    # keep a build (after it went live)
#   sh tools/versions.sh assemble <pkgdir> <ver>   # put the history into <pkgdir>
#
# ---- why subdirectories ----------------------------------------------------
# A published version has to stay reachable so that a player can go back to it
# (the page's 历史版本 drawer).  Two ways to do that on a static host: one
# project/subdomain per version, or one project with each version under its own
# path.  This uses paths: the page references everything relatively
# (`./app.js`, `new Worker('./worker.js')`, `await import('./render/...')`), so a
# copy of the site under /v/<version>/ simply works, with no DNS work and no
# cross-origin cache problems per release.
#
# The cost is that a deploy uploads the current tree PLUS every kept version --
# ~16 MB each.  That is why `archive` is a deliberate act and old versions are
# pruned by deleting their directory under build/releases/.
#
# ---- what a version number means here --------------------------------------
# `YYYY.MM.DD`, and the second release on the same day is `YYYY.MM.DD.2`.  The
# audience is players, not API consumers: "2026.10.13" is instantly comparable
# in a way "1.4.2" is not, and it needs no human judgement about what counts as
# a major or minor bump.  Exactness comes from version.json, which carries the
# git commit and the engine/renderer fingerprints next to it.
set -e

ROOT=$(cd "$(dirname "$0")/.." && pwd)
# build/releases/ is where published versions are kept.  Overridable so the
# acceptance suite can exercise archive/assemble in a temporary directory
# instead of writing into the real history.
REL=${MG_RELEASES_DIR:-$ROOT/build/releases}
MANIFEST=$REL/versions.json

# ---- next ------------------------------------------------------------------
next_version() {
    today=$(date +%Y.%m.%d)
    v=$today
    n=1
    while [ -d "$REL/$v" ]; do
        n=$((n + 1))
        v="$today.$n"
    done
    printf '%s' "$v"
}

# ---- manifest helpers ------------------------------------------------------
# One flat list, newest first, so the page and a shell `list` see the same thing.
manifest_add() {
    # manifest_add <version> <pkgdir>
    ver=$1
    pkg=$2
    python3 - "$MANIFEST" "$ver" "$pkg" <<'PY'
import json, os, sys, time, subprocess

path, ver, pkg = sys.argv[1], sys.argv[2], sys.argv[3]
try:
    with open(path, encoding="utf-8") as fh:
        doc = json.load(fh)
except Exception:
    doc = {"versions": []}
entries = [e for e in doc.get("versions", []) if e.get("version") != ver]

built, commit, note, engine = "", "", "", ""
vj = os.path.join(pkg, "version.json")
if os.path.exists(vj):
    try:
        with open(vj, encoding="utf-8") as fh:
            info = json.load(fh)
        built = info.get("builtAt", "")
        commit = info.get("commit", "")
        note = info.get("note", "")
        # The engine fingerprint travels with every manifest entry: a 参数集
        # (webapp/sharebits.js) carries the top 10 bits of it, so the page turns
        # "this code came from another build" into "switch to THAT version".
        # The date version cannot do that job -- it changes on page-only releases,
        # where the map is identical.
        engine = info.get("engine", "")
    except Exception:
        pass
entries.insert(0, {"version": ver, "builtAt": built, "commit": commit,
                   "note": note, "engine": engine,
                   "path": "/" if not built else "/v/%s/" % ver})
# The newest entry is what the root currently serves; the rest are historical.
for i, e in enumerate(entries):
    e["path"] = "/v/%s/" % e["version"]
entries[0]["path"] = "/"
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w", encoding="utf-8") as fh:
    json.dump({"versions": entries}, fh, ensure_ascii=False, indent=2)
    fh.write("\n")
PY
}

# ---- archive ---------------------------------------------------------------
# Keep a copy of what just went live.  `v/` is excluded: the history must not
# nest, or every release would re-upload every previous release inside itself.
# `versions.json` is excluded too -- it is regenerated by every assemble, and a
# stale copy inside a version directory would be misleading.
archive() {
    pkg=$1
    ver=$2
    [ -d "$pkg" ] || { echo "[versions] no such package: $pkg" >&2; exit 1; }
    [ -n "$ver" ] || { echo "[versions] archive needs a version" >&2; exit 1; }
    dst=$REL/$ver
    rm -rf "$dst"
    mkdir -p "$dst"
    # Absolute before the `cd` below: with a relative MG_RELEASES_DIR the copy
    # would otherwise be resolved against the package being archived, so every
    # file would land in the wrong place (or nowhere) -- which is how the
    # deployment checker caught it: the manifest listed a version whose bytes
    # were not there.
    dst=$(cd "$dst" && pwd)
    ( cd "$pkg" && find . -mindepth 1 -maxdepth 1 \
        ! -name v ! -name versions.json -exec cp -r {} "$dst/" \; )
    manifest_add "$ver" "$dst"
    printf '[versions] archived %s (%s)\n' "$ver" "$(du -sh "$dst" | cut -f1)"
}

# ---- assemble --------------------------------------------------------------
# Put every KEPT version into the package under /v/<version>/, then write the
# manifest the page reads at /versions.json.  The version being published is
# skipped: it is the root copy already.
assemble() {
    pkg=$1
    ver=$2
    [ -d "$pkg" ] || { echo "[versions] no such package: $pkg" >&2; exit 1; }
    [ -n "$ver" ] || { echo "[versions] assemble needs a version" >&2; exit 1; }

    n=0
    if [ -d "$REL" ]; then
        for d in "$REL"/*; do
            [ -d "$d" ] || continue
            v=$(basename "$d")
            [ "$v" = "$ver" ] && continue
            mkdir -p "$pkg/v/$v"
            # cp -r src/. dst/ copies the CONTENTS; plain `cp -r src dst` would
            # nest the source directory's name, which is right here but wrong
            # when dst already exists from a previous assemble.
            cp -r "$d/." "$pkg/v/$v/"
            n=$((n + 1))
        done
    fi

    # The manifest is regenerated from what is actually in the tree, so it can
    # never list a version whose bytes are not there.
    python3 - "$pkg/versions.json" "$pkg" "$ver" <<'PY'
import json, os, sys

out, pkg, current = sys.argv[1], sys.argv[2], sys.argv[3]
entries = []
vroot = os.path.join(pkg, "v")
kept = sorted(os.listdir(vroot)) if os.path.isdir(vroot) else []

def info(version, pkgdir):
    built = commit = note = engine = ""
    p = os.path.join(pkgdir, "version.json")
    if os.path.exists(p):
        try:
            with open(p, encoding="utf-8") as fh:
                d = json.load(fh)
            built, commit, note = d.get("builtAt", ""), d.get("commit", ""), d.get("note", "")
            # Read back out of the archived copy, so a restored version keeps the
            # engine id a 参数集 compares against (see manifest_add above).
            engine = d.get("engine", "")
        except Exception:
            pass
    return {"version": version, "builtAt": built, "commit": commit, "note": note,
            "engine": engine}

entries.append(dict(info(current, pkg), path="/"))
for v in sorted(kept, reverse=True):
    entries.append(dict(info(v, os.path.join(vroot, v)), path="/v/%s/" % v))
with open(out, "w", encoding="utf-8") as fh:
    json.dump({"current": current, "versions": entries}, fh, ensure_ascii=False, indent=2)
    fh.write("\n")
print("[versions] manifest: %d current + %d historical" % (1, len(kept)))
PY

    # A .wasm under /v/<version>/ is not covered by the root rules in
    # webapp/edgeone.json (`/*.wasm` and `/render/_framework/*.wasm`), and a
    # .wasm served as application/octet-stream makes the browser refuse to
    # instantiate it.  The pattern validator allows ONE `*` per pattern, so this
    # is one rule pair per version.  edgeone.json allows 100 header rules, hence
    # the practical ceiling of ~50 kept versions.
    python3 - "$pkg/edgeone.json" "$pkg/versions.json" <<'PY'
import json, sys

cfg_path, man_path = sys.argv[1], sys.argv[2]
# Missing or unparseable host config is a packaging bug, not something to paper
# over: without these rules a historical .wasm can be served as octet-stream,
# which makes the browser refuse to instantiate the renderer.
try:
    with open(cfg_path, encoding="utf-8") as fh:
        cfg = json.load(fh)
except FileNotFoundError:
    sys.exit("[versions] %s is missing (tools/package_webapp.sh copies it)" % cfg_path)
except ValueError as exc:
    sys.exit("[versions] %s is not valid JSON: %s" % (cfg_path, exc))
with open(man_path, encoding="utf-8") as fh:
    man = json.load(fh)

hist = [e["version"] for e in man["versions"] if e.get("path", "/") != "/"]
headers = [r for r in cfg.get("headers", [])
           if not any(h.get("value") == "application/wasm" and r.get("source", "").startswith("/v/")
                      for h in r.get("headers", []))]
for v in hist:
    headers.append({"source": "/v/%s/*.wasm" % v,
                    "headers": [{"key": "Content-Type", "value": "application/wasm"}]})
    headers.append({"source": "/v/%s/render/_framework/*.wasm" % v,
                    "headers": [{"key": "Content-Type", "value": "application/wasm"}]})
cfg["headers"] = headers
with open(cfg_path, "w", encoding="utf-8") as fh:
    json.dump(cfg, fh, ensure_ascii=False, indent=2)
    fh.write("\n")
print("[versions] edgeone.json: %d header rules for %d historical version(s)" % (len(headers), len(hist)))
PY
    printf '[versions] assembled %s (%d historical)\n' "$ver" "$n"
}

# ---- list ------------------------------------------------------------------
list_versions() {
    if [ ! -f "$MANIFEST" ]; then
        echo "[versions] nothing has been published yet (no $MANIFEST)"
        return 0
    fi
    python3 - "$MANIFEST" <<'PY'
import json, sys
with open(sys.argv[1], encoding="utf-8") as fh:
    doc = json.load(fh)
for e in doc.get("versions", []):
    print("  %-16s %-8s %-22s %s" % (e.get("version", "?"), e.get("path", "?"),
                                     e.get("builtAt", "?"), e.get("commit", "")))
PY
}

case "${1:-}" in
    next)     shift; next_version ;;
    list)     shift; list_versions ;;
    archive)  shift; archive "$@" ;;
    assemble) shift; assemble "$@" ;;
    *)
        cat >&2 <<'EOF'
usage: sh tools/versions.sh <command>

  next                        print the version the next build should carry
  list                        print the versions that have been published
  archive <pkgdir> <version>  keep <pkgdir> as <version> (after it went live)
  assemble <pkgdir> <version> put every kept version into <pkgdir> and write
                              <pkgdir>/versions.json, then extend edgeone.json
EOF
        exit 2
        ;;
esac
